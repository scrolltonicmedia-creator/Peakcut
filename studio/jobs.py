def create(source: dict, options: dict, enqueue=True, creator=None, kind="video") -> dict:
    jid = time.strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:10]
    c = creators.get(creator) if creator else None
    if c:
        d = creators.root(c["id"]) / ("live" if kind == "live" else "videos") / jid
        base = {**DEFAULTS, **{k: c[k] for k in ("max_clips", "min_len", "max_len", "style", "layout", "captions")},
                "hook_text": creators.clean_hook(c.get("hook_text")),
                "description_text": creators.clean_description(c.get("description_text"))}
    else:
        d, base, creator = config.user_dir(ctx.uid()) / "jobs" / jid, dict(DEFAULTS), None
    opts = {**base, **clean_options(options)}
    if opts["min_len"] >= opts["max_len"]:
        opts["min_len"] = max(5, opts["max_len"] - 5)
    job = {"id": jid, "user": ctx.uid(), "kind": kind, "creator": creator, "dir": str(d), "created": time.time(), "source": source,
           "options": opts, "status": "queued", "stage": "Waiting", "progress": 0.0,
           "title": source.get("name", ""), "uploader": "", "duration": 0, "clips": [], "error": None, "ai": {},
           "direction": (c or {}).get("clip_prompt", "")}
    d.mkdir(parents=True)
    with _lock:
        _jobs[jid] = job
        _by_user.setdefault(job["user"], {})[jid] = job
    save(job)
    if enqueue:
        _q.put(("job", jid, None), user=job["user"])
    return job


def enqueue(job):
    save(job)
    kind = "compilation" if job.get("kind") == "compilation" else "job"
    _q.put((kind, job["id"], None), user=job["user"])


def create_compilation(video_ids: list, title: str, target_minutes: int, narration_plan: str, enqueue_now=True) -> dict:
    """Create one horizontal long-form video from the best original sections of several source videos."""
    title = re.sub(r"\s+", " ", str(title or "")).strip()[:100]
    plan = str(narration_plan or "").strip()[:2000]
    if not title:
        raise ValueError("Give the long video a title.")
    if target_minutes not in (10, 15, 20):
        raise ValueError("Choose a 10, 15 or 20 minute video.")
    if len(plan) < 20:
        raise ValueError("Add a short original narration or commentary plan first.")
    ids = list(dict.fromkeys(str(x) for x in (video_ids if isinstance(video_ids, list) else []) if isinstance(x, str)))
    if not 2 <= len(ids) <= 12:
        raise ValueError("Choose between 2 and 12 finished source videos.")
    candidates, usable_videos = [], []
    for video_order, jid in enumerate(ids):
        source_job = get(jid)
        if not source_job or source_job.get("kind") != "video" or source_job.get("status") != "done":
            continue
        before = len(candidates)
        for clip_order, clip in enumerate(sorted(source_job.get("clips", []), key=lambda c: float(c.get("start", 0)))):
            if clip.get("status") != "done":
                continue
            path = Path(clip["src"]) if clip.get("src") else Path(str(source_job.get("source_path") or ""))
            duration = max(0.0, float(clip.get("end", 0)) - float(clip.get("start", 0)))
            if not path.is_file() or duration < 0.25:
                continue
            candidates.append({"job": jid, "clip": str(clip.get("id")), "score": float(clip.get("score") or 0),
                               "duration": duration, "order": (video_order, float(clip.get("start", 0)), clip_order),
                               "creator": source_job.get("creator")})
        if len(candidates) > before:
            usable_videos.append(jid)
    if len(usable_videos) < 2:
        raise ValueError("At least two selected videos need finished AI moments and their original footage.")
    target = target_minutes * 60.0
    ranked, chosen, total = sorted(candidates, key=lambda x: (-x["score"], x["order"])), [], 0.0
    for item in ranked:
        chosen.append(item)
        total += item["duration"]
        if total >= target:
            break
    chosen.sort(key=lambda x: x["order"])
    creators_used = {x["creator"] for x in chosen}
    creator = next(iter(creators_used)) if len(creators_used) == 1 else None
    job = create({"type": "compilation", "name": title, "count": len(usable_videos)}, {}, enqueue=False,
                 creator=creator, kind="compilation")
    expected = min(total, target)
    score = round(sum(x["score"] for x in chosen) / len(chosen))
    job.update(compilation_items=[[x["job"], x["clip"]] for x in chosen], target_seconds=target,
               narration_plan=plan, duration=expected, title=title, stage="Waiting to assemble long video")
    job["clips"] = [{"id": "longform", "start": 0.0, "end": expected, "status": "queued", "score": score,
                     "hook": "BEST MOMENTS", "title": title,
                     "description": "The strongest moments selected from multiple full videos and shaped into one long-form ScrollTonic story.",
                     "hashtags": ["ScrollTonic", "BestMoments", "Compilation", "Gaming"], "captions": False,
                     "style": "clean", "layout": "longform", "reason": f"The strongest {len(chosen)} moments from {len(usable_videos)} full videos, ready for your original narration."}]
    save(job)
    if enqueue_now:
        _q.put(("compilation", job["id"], None), user=job["user"])
    return job


def submit(fn):
    """Run any heavy task (a render, a cleanup) on the single worker, in order."""
    _q.put(("fn", ctx.bind(fn), None))


def submit_live(fn):
    """Live-stream renders and cleanups: their own worker, so a long video can never hold them up."""
    _live_q.put(ctx.bind(fn))


def _live_worker():
    while True:
        fn = _live_q.get()
        try:
            fn()
        except Exception:  # noqa: BLE001
            traceback.print_exc()


def delete(jid):
    with _lock:
        job = _jobs.pop(jid, None)
        if job:
            _by_user.get(job["user"], {}).pop(jid, None)
    if job:
        ctx.bump(job["user"])
        shutil.rmtree(job["dir"], ignore_errors=True)
    return bool(job)


def request_render(jid, cid, changes: dict):
    job = _jobs[jid]
    clip = next(c for c in job["clips"] if c["id"] == cid)
    new = dict(clip)
    if "captions" in changes:
        new.update(clean_options({"captions": changes["captions"]}))
    for k in ("start", "end"):
        if k in changes:
            new[k] = round(float(changes[k]), 2)
    if "src_offset" in clip:  # live clip: can only move inside the saved piece of stream
        new["start"] = max(new["start"], clip["src_offset"])
        new["end"] = min(new["end"], clip["src_end"])
    if not (math.isfinite(new["start"]) and math.isfinite(new["end"])) or new["start"] < 0:
        raise ValueError("Those times aren't valid.")
    if not 3 <= new["end"] - new["start"] <= 180:
        raise ValueError("A clip can be 3 to 180 seconds long.")
    for k in ("hook", "title", "description", "style", "layout"):
        if k in changes:
            new[k] = str(changes[k])[:{"hook": 60, "title": 100, "description": 2000}.get(k, 20)]
    if "hashtags" in changes:
        raw = changes["hashtags"] if isinstance(changes["hashtags"], list) else re.split(r"[\s,]+", str(changes["hashtags"]))
        tags = [re.sub(r"\W", "", str(tag).lstrip("#"))[:30] for tag in raw]
        new["hashtags"] = list(dict.fromkeys(tag for tag in tags if tag))[:15]
    if new.get("style") not in render.STYLES:
        new["style"] = DEFAULTS["style"]
    if new.get("layout") not in render.LAYOUTS:
        new["layout"] = DEFAULTS["layout"]
    clip.update(new, status="queued")
    save(job)
    _q.put(("clip", jid, cid))


def _write_post_text(job, clip):
    """Keep the JSON beside a finished clip in step with what the editor shows."""
    post = {k: clip.get(k) for k in ("title", "description", "hashtags", "hook", "start", "end", "score")}
    (Path(job["dir"]) / "clips" / f"{clip['id']}.json").write_text(json.dumps(post, indent=1), encoding="utf-8")


def rewrite_post(jid, cid):
    """Rewrite an existing clip's social post fields from its saved transcript, without rendering the video."""
    job = get(jid)
    if not job:
        raise KeyError("No such video")
    clip = next((c for c in job.get("clips", []) if c.get("id") == cid), None)
    if not clip:
        raise KeyError("No such clip")
    words_file = Path(job["dir"]) / "words.json"
    try:
        words = json.loads(words_file.read_text(encoding="utf-8")) if words_file.is_file() else []
    except (OSError, ValueError):
        words = []
    if not words and clip.get("fixed_words"):
        words = clip["fixed_words"]
    near = [w for w in words if clip["start"] - 1 <= float(w.get("s", -1)) <= clip["end"] + 1]
    text = " ".join(str(w.get("w", "")).strip() for w in near if str(w.get("w", "")).strip())
    if not text:
        text = " ".join(x for x in (clip.get("hook", ""), clip.get("title", ""), clip.get("description", ""),
                                      clip.get("reason", "")) if x)
    if not text.strip():
        raise ValueError("This older clip has no saved transcript or post text to rewrite.")
    direction = job.get("direction") or ""
    if job.get("creator"):
        direction = (creators.get(job["creator"]) or {}).get("clip_prompt") or direction
    usage.set_context(job.get("creator"), job.get("title") or "Existing clip")
    fresh = brain.describe(text, job.get("title") or "", job.get("uploader") or "", game=job.get("game"),
                           timeout=config.AI_TIMEOUT, direction=direction)
    brand = brain._brand_block()
    unique_description = fresh.get("description", "")
    if brand and unique_description.endswith(brand):
        unique_description = unique_description[:-len(brand)].strip()
    if not fresh.get("title") or not unique_description:
        raise RuntimeError("The AI did not return new post text. Check Settings, AI, then try again.")
    with _lock:
        clip.update(title=fresh["title"], description=fresh["description"],
                    hashtags=fresh.get("hashtags") or clip.get("hashtags") or [])
        _write_post_text(job, clip)
    save(job)
    return job


def render_one(job, clip, words):
    d = Path(job["dir"])
    clip["status"] = "rendering"
    save(job)
    try:
        if not clip.get("src") and not job.get("source_path"):
            _piece_again(job, clip)
        off = clip.get("src_offset", 0.0)
        src = Path(clip["src"]) if clip.get("src") else Path(job["source_path"])
        if not clip.get("src"):
            clip["end"] = min(clip["end"], job["duration"])
        local = dict(clip, start=clip["start"] - off, end=clip["end"] - off, hook=roman.to_roman(clip.get("hook") or ""))
        near = _caption_words(job, clip, words, off) if clip.get("captions", True) else []
        out = render.render_clip(src, d / "clips", clip["id"], local, near, job["width"], job["height"])
        clip.update(out, status="done", version=clip.get("version", 0) + 1, error=None)
        _write_post_text(job, clip)
        if clip["version"] == 1:
            clip.setdefault("made_at", time.time())
            creators.log(job["creator"], f"Clip ready (score {clip['score']}): {clip['title'] or clip['hook']}")
            save(job)
            for fn in on_clip_ready:
                try:
                    fn(job, clip)
                except Exception:  # noqa: BLE001
                    traceback.print_exc()
    except Exception as e:  # noqa: BLE001
        clip.update(status="error", error=safe.friendly(e, 400))
        creators.log(job["creator"], f"Clip failed: {safe.friendly(e, 200)}")
    save(job)


def _caption_words(job, clip, words, off):
    span = [round(clip["start"], 2), round(clip["end"], 2), "en2"]      # "en2": captions made always-English
    if clip.get("fixed_for") == span and clip.get("fixed_words") and not any(
            roman.needs_roman(w.get("w", "")) for w in clip["fixed_words"]):
        raw = clip["fixed_words"]          # already tidied for this exact span: no second AI call
    else:
        raw = [w for w in words if clip["start"] - 1 <= w["s"] <= clip["end"] + 1]
        try:
            usage.set_context(job.get("creator"), job.get("title") or "")
            raw = brain.english_captions(raw, job.get("lang") or "", job.get("title") or "",
                                         youtube_english=lambda: _english_part(job, clip))
            clip.update(fixed_words=raw, fixed_for=span)
        except Exception:  # noqa: BLE001 - captions still render with the words as heard
            pass
    # the last word on it: whatever was said, nothing is drawn in Hindi or Urdu script
    return [dict(w, s=w["s"] - off, e=w["e"] - off) for w in roman.words(raw)]


